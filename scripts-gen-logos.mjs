// Regenerates src/hl/logoData.ts from the MIT-licensed @web3icons/core icon set.
// Run: node scripts-gen-logos.mjs
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const base = './node_modules/@web3icons/core/dist/svgs';
const wanted = {
  BTC: 'tokens/branded/BTC', ETH: 'tokens/branded/ETH', SOL: 'tokens/branded/SOL', XRP: 'tokens/branded/XRP',
  DOGE: 'tokens/branded/DOGE', SUI: 'tokens/branded/SUI', LINK: 'tokens/branded/LINK', AVAX: 'tokens/branded/AVAX',
  kPEPE: 'tokens/branded/PEPE', HYPE: 'networks/branded/hyper-evm',
};
const out = {};
for (const [coin, path] of Object.entries(wanted)) {
  try {
    const mod = require(`${base}/${path}.svg.js`);
    const svg = (mod.default ?? Object.values(mod)[0]).replace(/\s*\n\s*/g, '').replace(' class="web3icons"', '');
    out[coin] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  } catch (e) {
    console.warn(`no icon for ${coin}: ${e.message}`);
  }
}
writeFileSync(
  'src/hl/logoData.ts',
  `// Generated by scripts-gen-logos.mjs from @web3icons/core (MIT). Do not edit by hand.\nexport const BUNDLED_LOGOS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log('bundled', Object.keys(out).join(' '));
