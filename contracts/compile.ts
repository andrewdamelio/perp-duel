/**
 * Compile DuelEscrow.sol with solc-js and write:
 *   contracts/out/DuelEscrow.json   abi + bytecode, used by the deploy script and tests
 *   src/chain/escrowAbi.ts          typed abi for the app and referee
 * Run: npm run contracts:build
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const solc = require('solc');
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

const input = {
  language: 'Solidity',
  sources: { 'DuelEscrow.sol': { content: readFileSync(join(here, 'DuelEscrow.sol'), 'utf8') } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    // HyperEVM runs the Cancun hardfork.
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
  },
};

const findImports = (path: string) => {
  try {
    return { contents: readFileSync(join(root, 'node_modules', path), 'utf8') };
  } catch {
    return { error: `Not found: ${path}` };
  }
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === 'error');
// Print everything about our own source, and only hard errors from dependencies.
for (const e of output.errors ?? []) {
  if (e.severity === 'error' || e.sourceLocation?.file === 'DuelEscrow.sol') console.error(e.formattedMessage);
}
if (errors.length) process.exit(1);

const contract = output.contracts['DuelEscrow.sol'].DuelEscrow;
const artifact = { abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}` };

mkdirSync(join(here, 'out'), { recursive: true });
writeFileSync(join(here, 'out', 'DuelEscrow.json'), JSON.stringify(artifact, null, 2));
writeFileSync(
  join(root, 'src', 'chain', 'escrowAbi.ts'),
  `// Generated by contracts/compile.ts. Do not edit by hand.\nexport const escrowAbi = ${JSON.stringify(contract.abi, null, 2)} as const;\n`,
);
console.log(`DuelEscrow compiled: ${(artifact.bytecode.length - 2) / 2} bytes of init code`);
