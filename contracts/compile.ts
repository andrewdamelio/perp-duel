/**
 * Compile the contracts with solc-js and write:
 *   contracts/out/<Name>.json   abi + bytecode, used by the deploy script and tests
 *   src/chain/arenaAbi.ts       typed abi for the app and the bot
 * Run: npm run contracts:build
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const solc = require('solc');
const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const names = ['DuelArena', 'MockPrices'];

const input = {
  language: 'Solidity',
  sources: Object.fromEntries(names.map((n) => [`${n}.sol`, { content: readFileSync(join(here, `${n}.sol`), 'utf8') }])),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    // HyperEVM runs the Cancun hardfork.
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
  },
};

const findImports = (path: string) => {
  try {
    return { contents: readFileSync(join(root, 'node_modules', path), 'utf8') };
  } catch {
    return { error: `Not found: ${path}` };
  }
};

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
// Print everything about our own sources, and only hard errors from dependencies.
for (const e of output.errors ?? []) {
  if (e.severity === 'error' || names.some((n) => e.sourceLocation?.file === `${n}.sol`)) console.error(e.formattedMessage);
}
if ((output.errors ?? []).some((e: { severity: string }) => e.severity === 'error')) process.exit(1);

mkdirSync(join(here, 'out'), { recursive: true });
for (const name of names) {
  const contract = output.contracts[`${name}.sol`][name];
  const artifact = { abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}` };
  writeFileSync(join(here, 'out', `${name}.json`), JSON.stringify(artifact, null, 2));
  console.log(`${name}: ${contract.evm.deployedBytecode.object.length / 2} bytes deployed`);
}
writeFileSync(
  join(root, 'src', 'chain', 'arenaAbi.ts'),
  `// Generated by contracts/compile.ts. Do not edit by hand.\nexport const arenaAbi = ${JSON.stringify(output.contracts['DuelArena.sol'].DuelArena.abi, null, 2)} as const;\n`,
);
